/**
 * Formats scan results into Markdown table and summary for GitHub/GitLab PRs and issues.
 */
export function formatMarkdownReport(scanResult) {
  const {
    projectName,
    projectVersion,
    totalDependencies,
    directCount,
    transitiveCount,
    findings,
    summary,
    durationMs,
    thresholdBreached,
    failThreshold,
  } = scanResult;

  const lines = [];

  lines.push(`# 🛡️ Vulnerability Scan Report: ${projectName} (v${projectVersion})`);
  lines.push('');
  lines.push(`- **Scan Date**: ${new Date().toUTCString()}`);
  lines.push(`- **Duration**: ${(durationMs / 1000).toFixed(2)}s`);
  lines.push(`- **Dependencies Scanned**: ${totalDependencies} (${directCount} direct, ${transitiveCount} transitive)`);
  lines.push(`- **Data Source**: [OSV.dev](https://osv.dev)`);
  lines.push(`- **Status**: ${thresholdBreached ? '❌ **Failed** (threshold `' + failThreshold + '` breached)' : '✅ **Passed**'}`);
  lines.push('');

  lines.push('## Severity Summary');
  lines.push('');
  lines.push('| Critical | High | Medium | Low | Total Vulnerabilities |');
  lines.push('|:---:|:---:|:---:|:---:|:---:|');
  lines.push(`| **${summary.critical}** | **${summary.high}** | **${summary.medium}** | **${summary.low}** | **${findings.length}** |`);
  lines.push('');

  if (findings.length === 0) {
    lines.push('🎉 **No known open-source vulnerabilities found!**');
    return lines.join('\n');
  }

  lines.push('## Vulnerabilities Detected');
  lines.push('');
  lines.push('| Severity | Package | Installed | Scope | Advisory ID | CVE | Recommended Fix |');
  lines.push('|---|---|---|---|---|---|---|');

  for (const f of findings) {
    const sevBadge = `**${f.severity.level}**${f.severity.score ? ` (${f.severity.score})` : ''}`;
    const scope = f.isDirect ? 'Direct' : `Transitive (${f.dependencyChain[0]})`;
    const cve = f.aliases && f.aliases.length > 0 ? f.aliases.join(', ') : '-';
    const fix = f.fixedVersion ? `\`>= ${f.fixedVersion}\`` : '_No fix_';
    const link = `[${f.id}](https://osv.dev/vulnerability/${f.id})`;

    lines.push(`| ${sevBadge} | \`${f.packageName}\` | \`${f.packageVersion}\` | ${scope} | ${link} | ${cve} | ${fix} |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('_Generated by `vuln-scanner` POC using OSV.dev._');
  return lines.join('\n');
}
